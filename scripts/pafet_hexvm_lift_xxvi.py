#!/usr/bin/env python3
"""Literal C++ translation of Hex-VM CFGs; no native-code execution at runtime."""
import argparse,collections,hashlib,json,pathlib,re
import capstone,pefile
from pafet_audit_xxiv import cfg,BASE,ROOT
from pafet_lift_xxiv import emit,operand

def extended(md,i):
    op=i.mnemonic;os=i.operands
    if op=='xorps':
        # Identical bitwise register/memory operation to PXOR.
        a,b=[operand(md,o) for o in os]
        return '{uint8_t a[16],b[16];vector_get('+a+',a);vector_get('+b+',b);for(int k=0;k<16;k++)a[k]^=b[k];vector_put('+a+',a);}'
    if op=='sar':
        a,b=[operand(md,o) for o in os];n=os[0].size*8
        return '{const auto dst='+a+';unsigned count=unsigned(get('+b+'))&'+str(63 if n==64 else 31)+';if(count){uint64_t v=get(dst);bool neg=(v>>'+str(n-1)+')!=0;uint64_t result=count>='+str(n)+'?(neg?mask('+str(n)+'):0):uint64_t(signed_value(v,'+str(n)+')>>count);put(dst,result);bit(CF,count>='+str(n)+'?neg:((v>>(count-1))&1));zsp(result,'+str(n)+');c.defined&=~AF;if(count==1)bit(OF,false);else c.defined&=~OF;}}'
    if op=='cqo':return 'c.r[2]=(c.r[0]>>63)?~uint64_t(0):0;'
    if op=='cdqe':return 'c.r[0]=uint64_t(int64_t(int32_t(c.r[0])));'
    if op=='idiv':
        a=operand(md,os[0]);assert os[0].size==8
        return 'signed_divide_accumulator(get('+a+'));'
    if op=='imul' and len(os)==1:
        a=operand(md,os[0]);assert os[0].size==8
        return 'signed_multiply_accumulator(get('+a+'));'
    if op=='movaps':
        a,b=[operand(md,o) for o in os]
        return '{uint8_t v[16];if(('+a+'.kind==2&&address('+a+')%16)||('+b+'.kind==2&&address('+b+')%16))throw Fault(4,c.rip,"unaligned MOVAPS");vector_get('+b+',v);vector_put('+a+',v);}'
    if op=='psrldq':
        a=operand(md,os[0]);amount=os[1].imm
        return '{uint8_t x[16],v[16]{};vector_get('+a+',x);for(int k=0;k<16;k++)if(k+'+str(amount)+'<16)v[k]=x[k+'+str(amount)+'];vector_put('+a+',v);}'
    if op=='movq':
        a,b=[operand(md,o) for o in os]
        return '{uint8_t v[16];vector_get('+b+',v);uint64_t x;std::memcpy(&x,v,8);put('+a+',x);}'
    if op=='movsd':
        a,b=[operand(md,o) for o in os]
        if os[0].type==1:
            return '{uint8_t v[16]{};uint64_t x=get('+b+');std::memcpy(v,&x,8);vector_put('+a+',v);}'
        return '{uint8_t v[16];vector_get('+b+',v);uint64_t x;std::memcpy(&x,v,8);put('+a+',x);}'
    return emit(md,i)

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--full',action='store_true');args=ap.parse_args()
    pe=pefile.PE(str(ROOT/'pafet.bin'));pending=[BASE+0x80000];functions={};instructions={}
    if args.full:
        pending += [BASE+0x804c0,BASE+0x88990,BASE+0x39dee0,BASE+0x889e0,BASE+0x889f0,BASE+0x3ca648]
        pending += [int.from_bytes(pe.get_data(0x3f1ba0+8*i,8),'little') for i in range(5)]
        pending += [int.from_bytes(pe.get_data(0x3dbca0+8*i,8),'little') for i in range(8)]
        # Four remap domains contain 62 pointers each (61 distinct bodies).
        # These are indirect native targets and do not appear as CALL edges.
        for group in range(4):
            table=int.from_bytes(pe.get_data(0x3e4fb0+8*group,8),'little')
            pending += [int.from_bytes(pe.get_data(table-BASE+8*i,8),'little') for i in range(62)]
        # The small expression VM in 0x48e10 uses R9 as an image base set
        # earlier in its block. Its bounded 11-entry switch differs from the
        # adjacent-LEA pattern recognized by the shared recursive CFG walker.
        pending += [BASE+int.from_bytes(pe.get_data(0x491f8+4*i,4),'little') for i in range(11)]
    while pending:
        entry=pending.pop()
        if entry in functions:continue
        ins,info=cfg(pe,entry);functions[entry]=info;instructions.update(ins)
        pending.extend(c['target'] for c in info['calls'] if c['target'] is not None and BASE<=c['target']<BASE+(0x3a0000 if args.full else 0x390000) and c['target'] not in functions)
    md=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_64);md.detail=True
    lines=['// Generated by scripts/pafet_hexvm_lift_xxvi.py; keep separate from reduced core.',
           '#include "pafet_hexvm_cpu_xxvi.h"','namespace pafet_xxiv {','void Machine::step(){','switch(canonical(c.rip)){']
    for pc,i in sorted(instructions.items()):
        lines += [f'case UINT64_C(0x{pc:x}): {{next=c.rip+{i.size}; // {i.mnemonic} {i.op_str}',extended(md,i),'c.rip=next;return;}']
    lines += ['default:if(trampoline())return;throw Fault(3,c.rip,"instruction not in Hex-VM translated CFG");','}','}','}']
    path=ROOT/'src'/('pafet_hexvm_executor_lifted_xxvi.cpp' if args.full else 'pafet_hexvm_lifted_xxvi.cpp')
    sources=[]
    if args.full:
        directory=ROOT/'src/hexvm_lifted_xxvi';directory.mkdir(exist_ok=True)
        groups=collections.defaultdict(list)
        for pc,i in sorted(instructions.items()):groups[(pc-BASE)>>14].append(i)
        calls=[];methods='get put address arithmetic logic signed_value imul mul divide shift bitop push pop condition vector_get vector_put flag bit zsp mask signed_divide_accumulator signed_multiply_accumulator'.split()
        pattern=r'\b('+'|'.join(methods)+r')\('
        for group,items in sorted(groups.items()):
            name=f'hexvm_part_{group:x}';calls.append((group,name));part=directory/f'part_{group:x}.cpp'
            body=['// Generated literal x64 semantics.','#include "../pafet_hexvm_cpu_xxvi.h"','namespace pafet_xxiv {',
                  f'bool {name}(Machine& m){{auto& c=m.c;auto& next=m.next;switch(m.canonical(c.rip)){{']
            for i in items:body += [f'case UINT64_C(0x{i.address:x}): {{next=c.rip+{i.size}; // {i.mnemonic} {i.op_str}',
                                   re.sub(pattern,r'm.\1(',extended(md,i)),'c.rip=next;return true;}']
            body+=['default:return false;','}}','}'];text='\n'.join(body)+'\n'
            if not part.exists() or part.read_text(encoding='utf-8')!=text:part.write_text(text,encoding='utf-8')
            sources.append(part)
        lines=['// Generated partition dispatcher.','#include "pafet_hexvm_cpu_xxvi.h"','namespace pafet_xxiv {']
        lines += [f'bool {name}(Machine&);' for _,name in calls]
        lines += ['void Machine::step(){bool found=false;switch((canonical(c.rip)-UINT64_C(0x140000000))>>14){']
        lines += [f'case {group}:found={name}(*this);break;' for group,name in calls]
        lines += ['}if(found)return;if(trampoline())return;throw Fault(3,c.rip,"instruction not in Hex-VM translated CFG");}','}']
    text='\n'.join(lines)+'\n'
    if not path.exists() or path.read_text(encoding='utf-8')!=text:path.write_text(text,encoding='utf-8')
    sources.insert(0,path)
    report={'pe_sha256':hashlib.sha256((ROOT/'pafet.bin').read_bytes()).hexdigest(),'source_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
            'functions':{hex(k):v['instructions'] for k,v in functions.items()},'instructions':len(instructions),
            'mnemonics':dict(collections.Counter(i.mnemonic for i in instructions.values())),
            'untranslated_direct_calls':sorted({hex(c['target']) for f in functions.values() for c in f['calls'] if c['target'] is not None and c['target'] not in functions}),
            'sources':[p.relative_to(ROOT).as_posix() for p in sources],
            'source_hashes':{p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in sources},
            'runtime_hashes':{p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in ['src/pafet_hexvm_cpu_xxvi.h','src/pafet_hexvm_host_xxvi.h','src/main_hexvm_literal_xxvi.cpp','src/main_hexvm_standalone_xxvi.cpp']},
            'scope':'literal executor CFG and all four remap domains; host boundaries separate' if args.full else 'literal decoder/remap and internal direct dependencies'}
    (ROOT/'jack_xxvi_evidence'/('executor_lift_manifest.json' if args.full else 'decoder_lift_manifest.json')).write_text(json.dumps(report,indent=2)+'\n')
    if args.full:
        anchors={}
        for pc,i in instructions.items():
            if BASE+0x804c0<=pc<BASE+0x889e0 and i.mnemonic=='cmp' and i.op_str.startswith('eax, '):
                j=instructions.get(pc+i.size)
                if j and j.mnemonic in ('jg','jl','ja','jb'):j=instructions.get(j.address+j.size)
                if j and j.mnemonic in ('je','jne'):anchors[i.operands[1].imm]=j.operands[0].imm if j.mnemonic=='je' else j.address+j.size
        blocks=json.loads((ROOT/'jack_xxvi_evidence/blocks.json').read_bytes())
        rows=[{'pc':b['pc'],'native_entry':hex(anchors[int(b['pc'],16)]),'literal_translation':True,
               'reduced_semantics':b['semantic_status']} for b in blocks]
        (ROOT/'jack_xxvi_evidence/literal_program_map.json').write_text(json.dumps(rows,indent=2)+'\n')
    print('translated',len(instructions),'instructions in',len(functions),'functions')

if __name__=='__main__':main()
